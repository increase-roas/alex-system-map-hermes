#!/usr/bin/env python3
"""Generate browser-safe exact copies. --check never writes."""
import json
import sys
from pathlib import Path
root = Path(__file__).resolve().parent
names = ["asset_guard.py", "read_gate.py", "hermes_guard.py"]
code = {name: (root / name).read_text() for name in names}
output = "// Generated by pro-map-guardrails/bundle.py. Do not hand-edit.\nexport const GUARD_CODE: Record<string, string> = " + json.dumps(code, indent=2) + ";\n"
target = root.parent / "pro-map-guardrail-code.ts"
if "--check" in sys.argv:
    if not target.exists() or target.read_text() != output:
        raise SystemExit("FAIL: displayed scripts differ from tested source")
    print("PASS: 3 displayed hook scripts exactly match canonical files")
else:
    target.write_text(output)
    print("Bundled 3 hook scripts")
